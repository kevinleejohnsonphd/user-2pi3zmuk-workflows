def assess_and_assign_tier_node(state: MedicalTriageAgentThatAnalyzesState) -> Dict[str, Any]:
    """
    Analyze patient symptoms, test results, and doctor observations to determine triage tier 
    (1=immediate, 2=within 1 year, 3=beyond 1 year) and provide reasoning for the decision.
    """
    from langchain_anthropic import ChatAnthropic
    
    messages = state.get("messages", [])
    user_input = messages[-1].content if messages else ""

    if not user_input:
        return {
            "messages": [AIMessage(content="Please provide patient information for triage assessment.")],
        }

    llm = ChatAnthropic(model="claude-sonnet-4-5-20250929", temperature=0, api_key=os.getenv("ANTHROPIC_API_KEY"))

    system_prompt = '''You are an expert medical triage specialist. Your role is to analyze patient presentations and assign appropriate triage tiers based on urgency and severity.

**Triage Tier Definitions**:
- **Tier 1 (Immediate)**: Life-threatening emergencies requiring immediate intervention (within minutes to hours)
  - Examples: STEMI, acute appendicitis, perforated viscus, severe trauma, acute stroke, respiratory failure
  - Key indicators: Hemodynamic instability, acute organ failure, peritoneal signs, severe pain with concerning findings

- **Tier 2 (Within 1 year)**: Serious conditions requiring timely but not emergent care (within days to months)
  - Examples: Suspected malignancy, uncontrolled hypertension with risk factors, conditions requiring prompt workup
  - Key indicators: High suspicion for serious disease, significant risk factors, need for definitive diagnosis/treatment but stable currently

- **Tier 3 (Beyond 1 year)**: Stable, chronic, or benign conditions manageable with routine care
  - Examples: Mild musculoskeletal pain, seasonal allergies, stable chronic conditions
  - Key indicators: No acute distress, benign presentation, self-limiting conditions, adequate function

**Assessment Process**:
1. **Identify presenting symptoms and timeline**: What is the chief complaint? How long has it been present?
2. **Evaluate vital signs and objective findings**: Are there signs of hemodynamic compromise or organ dysfunction?
3. **Consider test results and imaging**: Do findings suggest acute pathology or serious disease?
4. **Assess risk factors and context**: Age, comorbidities, family history, social situation
5. **Determine urgency**: Is this life-threatening now? Could it become life-threatening soon? Or is it stable?

**Special Considerations**:
- **Elderly patients**: May have atypical presentations; lower threshold for Tier 1
- **Chest pain**: Always take seriously; err on side of caution
- **Altered mental status**: Often indicates serious underlying pathology
- **Incomplete data**: Work with available information; acknowledge limitations but still provide best assessment
- **Vague symptoms**: Consider differential diagnosis; may assign provisional tier with recommendation for complete evaluation

**Output Format**:
Provide a clear, structured assessment in plain text (NOT JSON):

Based on the assessment, this patient is assigned **Triage Tier [1/2/3] ([Immediate/Within 1 year/Beyond 1 year])**.

Reasoning:
- [Key clinical finding 1]
- [Key clinical finding 2]
- [Risk assessment]
- [Urgency justification]

Recommendation: [Specific next steps and timeline]

**Important**: 
- Always provide a tier assignment (1, 2, or 3)
- If data is incomplete, acknowledge this but still provide best assessment based on available information
- Use clinical reasoning to justify the tier
- Be specific about what makes this urgent or non-urgent
- Format output as readable prose, not JSON'''

    response = llm.invoke([
        SystemMessage(content=system_prompt),
        HumanMessage(content=f'''Please perform a triage assessment on this patient presentation:

{user_input}

Analyze the symptoms, vital signs, test results, and clinical context to assign the appropriate triage tier (1, 2, or 3) with clear reasoning.''')
    ])

    ai_content = response.content

    # Extract tier from response for state tracking
    tier = None
    if "Tier 1" in ai_content or "tier 1" in ai_content.lower():
        tier = 1
    elif "Tier 2" in ai_content or "tier 2" in ai_content.lower():
        tier = 2
    elif "Tier 3" in ai_content or "tier 3" in ai_content.lower():
        tier = 3

    return {
        "messages": [AIMessage(content=ai_content)],
        "triage_tier": tier,
        "reasoning": ai_content
    }