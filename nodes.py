def assess_and_assign_tier_node(state: MedicalTriageAgentThatAnalyzesState) -> Dict[str, Any]:
    '''
    Analyze patient symptoms, test results, and doctor observations to determine triage tier 
    (1=immediate, 2=within 1 year, 3=beyond 1 year) and provide reasoning for the decision.
    
    Returns concise bullet-point assessment (5-8 sentences).
    '''
    messages = state.get("messages", [])
    user_input = messages[-1].content if messages else ""

    if not user_input:
        return {
            "messages": [AIMessage(content="Please provide patient information to assess.")],
        }

    llm = ChatAnthropic(model="claude-sonnet-4-5-20250929", temperature=0, api_key=os.getenv("ANTHROPIC_API_KEY"))

    system_prompt = '''You are a medical triage expert. Analyze patient information and assign a triage tier.

**Triage Tiers:**
- **Tier 1 (Immediate)**: Life-threatening emergencies requiring immediate intervention (STEMI, acute appendicitis, perforated viscus, severe sepsis, acute abdomen with peritoneal signs, elderly with altered mental status and hemodynamic instability)
- **Tier 2 (Within 1 year)**: Serious conditions requiring timely intervention within weeks to months (Stage 2 hypertension with risk factors, suspicious malignancy, ambiguous chest pain requiring cardiac workup)
- **Tier 3 (Beyond 1 year)**: Stable chronic conditions or benign issues (mild musculoskeletal pain, seasonal allergies, stable chronic conditions)

**Assessment Process:**
1. Identify key clinical findings (symptoms, vitals, test results, physical exam)
2. Recognize life-threatening vs serious vs benign patterns
3. Consider risk factors and potential for deterioration
4. Assign appropriate tier based on urgency and severity
5. Provide clear clinical reasoning

**Special Considerations:**
- Elderly patients with subtle changes may indicate serious illness (assign Tier 1 if altered mental status + vital sign changes)
- Chest pain in adults requires careful evaluation (Tier 2 if ambiguous, Tier 1 if clear ACS)
- Stage 2 hypertension with risk factors = Tier 2 (requires timely treatment, not beyond 1 year)
- Suspicious malignancy (BI-RADS 5) = Tier 2 (urgent but not emergent)
- Acute surgical abdomen = Tier 1 (peritoneal signs indicate emergency)
- When data is insufficient, state this clearly and provide provisional assessment with caveats

**CRITICAL OUTPUT FORMAT:**
Your response MUST be 5-8 sentences in concise bullet format. Structure as follows:

**Triage Tier [X]: [Brief descriptor]**

• [Key finding 1 supporting tier assignment]
• [Key finding 2 supporting tier assignment]
• [Risk assessment or clinical significance]
• [Reasoning for tier choice]
• [Recommendation for next steps]

**Example (correct format):**
**Triage Tier 1: Immediate**

• Classic STEMI presentation with ST-elevation on ECG and elevated troponin
• Severe chest pain with radiation and diaphoresis indicates acute MI
• Hemodynamic instability (BP 160/95, HR 110) suggests high-risk event
• Life-threatening emergency requiring immediate catheterization
• Activate cardiac emergency protocol and prepare for urgent intervention

Do NOT write long paragraphs. Keep each bullet to one sentence. Total response: 5-8 sentences maximum.'''

    response = llm.invoke([
        SystemMessage(content=system_prompt),
        HumanMessage(content=f'''Assess this patient and assign triage tier:

{user_input}

Remember: Respond in 5-8 sentences using bullet format as shown in the instructions.''')
    ])

    ai_content = response.content

    # Extract tier from response for state tracking
    tier_match = re.search(r'Tier\s+(\d)', ai_content)
    tier = int(tier_match.group(1)) if tier_match else None

    return {
        "messages": [AIMessage(content=ai_content)],
        "triage_tier": tier,
        "reasoning": ai_content,
        "confidence_level": "high" if tier else "low"
    }