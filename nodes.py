def assess_and_assign_tier_node(state: MedicalTriageAgentThatAnalyzesState) -> Dict[str, Any]:
    """
    Analyze patient symptoms, test results, and doctor observations to determine triage tier 
    (1=immediate, 2=within 1 year, 3=beyond 1 year) and provide reasoning for the decision.
    
    This node uses chain-of-thought reasoning to:
    1. Assess data completeness and quality
    2. Identify life-threatening conditions requiring immediate care (Tier 1)
    3. Recognize moderate conditions requiring timely intervention (Tier 2)
    4. Classify stable, non-urgent conditions (Tier 3)
    5. Acknowledge uncertainty when data is insufficient
    """
    messages = state.get("messages", [])
    user_input = messages[-1].content if messages else ""

    if not user_input:
        return {
            "messages": [AIMessage(content="Please provide patient information for triage assessment.")],
            "triage_tier": None,
            "confidence_level": "none"
        }

    llm = ChatAnthropic(model="claude-sonnet-4-5-20250929", temperature=0, api_key=os.getenv("ANTHROPIC_API_KEY"))

    system_prompt = '''You are an expert medical triage specialist. Your role is to analyze patient presentations and assign appropriate triage tiers based on urgency and severity.

**TRIAGE TIER DEFINITIONS**:
- **Tier 1 (Immediate)**: Life-threatening emergencies requiring immediate intervention (within minutes to hours)
  * Examples: STEMI, acute appendicitis, perforated viscus, severe sepsis, acute stroke
  * Key indicators: Hemodynamic instability, acute organ failure, surgical emergencies, peritoneal signs
  
- **Tier 2 (Within 1 year)**: Moderate conditions requiring timely but non-emergent intervention (within weeks to months)
  * Examples: Stage 2 hypertension, suspicious masses (BI-RADS 5), newly diagnosed diabetes, stable angina
  * Key indicators: Significant cardiovascular risk, high suspicion for malignancy, chronic disease requiring treatment initiation
  * **CRITICAL**: Newly diagnosed Stage 2 hypertension (≥140/90) with risk factors = Tier 2, NOT Tier 3
  
- **Tier 3 (Beyond 1 year)**: Stable, non-urgent conditions manageable with routine care
  * Examples: Mild musculoskeletal pain, seasonal allergies, stable chronic conditions
  * Key indicators: No functional impairment, benign pathology, self-limiting conditions

**CHAIN-OF-THOUGHT REASONING PROCESS**:

1. **Data Completeness Assessment**:
   - Identify what clinical information is provided (symptoms, vitals, labs, imaging, physical exam)
   - Flag missing critical data (e.g., vital signs, key test results)
   - Determine if available data is sufficient for confident triage

2. **Risk Stratification**:
   - Identify red flags for life-threatening conditions (chest pain + ST elevation, peritoneal signs, altered mental status in elderly)
   - Assess for moderate risk requiring timely intervention (Stage 2 HTN + family history, suspicious masses)
   - Recognize stable, low-risk presentations

3. **Tier Assignment Logic**:
   - **Tier 1 triggers**: Acute cardiac events, surgical emergencies, hemodynamic instability, acute organ dysfunction
   - **Tier 2 triggers**: Newly diagnosed chronic disease requiring treatment, high suspicion for malignancy, significant cardiovascular risk
   - **Tier 3 triggers**: Mild symptoms, no functional impairment, benign conditions

4. **Uncertainty Acknowledgment**:
   - When data is insufficient or ambiguous, EXPLICITLY state this
   - Provide provisional tier assignment with clear caveats
   - Request specific additional information needed for confident assessment

**CRITICAL RULES**:
1. **Stage 2 Hypertension (≥140/90) with cardiovascular risk factors = Tier 2**, not Tier 3
   - Requires treatment initiation within weeks to months to prevent complications
   - Even if patient is currently asymptomatic and stable
   
2. **Insufficient data = LOW CONFIDENCE assessment**:
   - State: "Based on limited information provided, I cannot confidently assign a triage tier"
   - Provide provisional tier with explicit caveats
   - List specific data needed for proper assessment
   
3. **Elderly patients with subtle changes = HIGH RISK**:
   - Altered mental status, borderline vitals, or vague symptoms may indicate serious illness
   - Lower threshold for Tier 1 assignment in geriatric patients

4. **Ambiguous presentations = Tier 2 (cautious approach)**:
   - When cardiac etiology cannot be excluded but is uncertain → Tier 2 for definitive testing
   - Do not assign Tier 1 unless clear emergency criteria met

**OUTPUT FORMAT**:
Return JSON with the following structure:
{{
  "confidence_level": "high/medium/low",
  "data_completeness": "complete/partial/insufficient",
  "tier": 1/2/3,
  "reasoning": "Detailed clinical reasoning with specific data points cited",
  "recommendation": "Specific next steps and timeline",
  "caveats": "Any limitations or uncertainties in the assessment (required if confidence is low)"
}}

**IMPORTANT**: 
- Always cite specific clinical findings from the input
- Use medical terminology appropriately
- Acknowledge when data is insufficient
- Provide clear, actionable recommendations'''

    response = llm.invoke([
        SystemMessage(content=system_prompt),
        HumanMessage(content=f'''Analyze this patient presentation and assign a triage tier:

{user_input}

Think through the assessment step-by-step, then return your analysis in JSON format.''')
    ])

    try:
        result = json.loads(response.content)
        
        confidence = result.get("confidence_level", "medium")
        data_completeness = result.get("data_completeness", "partial")
        tier = result.get("tier")
        reasoning = result.get("reasoning", "")
        recommendation = result.get("recommendation", "")
        caveats = result.get("caveats", "")

        # Format output for user
        if confidence == "low" or data_completeness == "insufficient":
            ai_content = f'''**⚠️ Triage Assessment — Limited Confidence**

**Data Completeness**: {data_completeness.capitalize()}
**Confidence Level**: {confidence.capitalize()}

**Provisional Tier Assignment**: Tier {tier if tier else "Unknown"}

**Important Caveats**:
{caveats if caveats else "Insufficient information provided for confident triage assessment."}

**Reasoning**:
{reasoning}

**Recommendation**:
{recommendation}

**Additional Information Needed**:
To provide a confident triage assessment, please provide:
- Complete vital signs (BP, HR, temperature, respiratory rate, O2 saturation)
- Relevant physical examination findings
- Pertinent laboratory results
- Imaging results if available
- Timeline and progression of symptoms
- Patient's baseline health status and comorbidities'''
        else:
            tier_label = {1: "Immediate", 2: "Within 1 Year", 3: "Beyond 1 Year"}.get(tier, "Unknown")
            ai_content = f'''**Triage Assessment — Tier {tier} ({tier_label})**

**Confidence Level**: {confidence.capitalize()}

**Reasoning**:
{reasoning}

**Recommendation**:
{recommendation}'''

        return {
            "messages": [AIMessage(content=ai_content)],
            "triage_tier": tier,
            "reasoning": reasoning,
            "recommendation": recommendation,
            "confidence_level": confidence
        }

    except (json.JSONDecodeError, ValueError) as e:
        logger.warning(f"Failed to parse JSON response: {e}")
        # Fallback: return raw response with low confidence indicator
        ai_content = f'''**Triage Assessment**

{response.content}

**Note**: This assessment was generated but could not be structured. Please review carefully and consider requesting additional clinical information if needed.'''
        
        return {
            "messages": [AIMessage(content=ai_content)],
            "confidence_level": "low"
        }